async def run_consolidation(
    store: MemoryStore,
    llm_client: LLMClient,
    embeddings: EmbeddingsService,
    tenant_id: str,
    entity_id: Optional[str] = None
) -> ConsolidationResult:
    """
    Run memory consolidation for a tenant or entity.
    
    Args:
        store: Memory store
        llm_client: LLM client
        embeddings: Embeddings service
        tenant_id: Tenant identifier
        entity_id: Optional specific entity (if None, process all)
        
    Returns:
        ConsolidationResult with statistics
    """
    distiller = InsightDistiller(
        store=store,
        llm_client=llm_client,
        embeddings=embeddings
    )
    
    if entity_id:
        return await distiller.distill_for_entity(tenant_id, entity_id)
    else:
        return await distiller.distill_for_tenant(tenant_id)


def print_consolidation_report(result: ConsolidationResult) -> None:
    """Print a human-readable consolidation report."""
    print("\n" + "=" * 60)
    print("CONSOLIDATION REPORT")
    print("=" * 60)
    
    print(f"\n📊 Summary")
    print(f"   Tenant: {result.tenant_id}")
    if result.entity_id:
        print(f"   Entity: {result.entity_id[:8]}...")
    print(f"   Claims analyzed: {result.claims_analyzed}")
    print(f"   Insights created: {result.insights_created}")
    print(f"   Insights strengthened: {result.insights_strengthened}")
    print(f"   Insights merged: {result.insights_merged}")
    
    if result.new_insight_ids:
        print(f"\n📝 New Insights ({len(result.new_insight_ids)})")
        for iid in result.new_insight_ids[:5]:
            print(f"   • {iid[:12]}...")
        if len(result.new_insight_ids) > 5:
            print(f"   ... and {len(result.new_insight_ids) - 5} more")
    
    print("=" * 60)
