"""
SAM Memory Consolidation

Phase 4: Insight distillation from Claims.

This module handles the "consolidation" phase of memory - periodically analyzing
accumulated Claims to generate actionable Insights. This mimics how human memory
consolidates episodic experiences into semantic knowledge during sleep/rest.

Key operations:
1. Claim clustering - Group related claims by entity/topic
2. Insight distillation - Generate prescriptive insights from descriptive claims
3. Insight deduplication - Merge similar insights, strengthening confidence
4. Relationship tracking - Create SUPPORTS edges from claims to insights

Example flow:
    Claims:
    - "User:Alice prefers email communication"
    - "User:Alice responds within 1 hour to emails"
    - "User:Alice rarely answers phone calls"
    
    → Distilled Insight:
    - "Contact Alice via email for fastest response" (derived from 3 claims)
"""

import json
from datetime import datetime
from typing import List, Optional, Dict, Any, Tuple
from dataclasses import dataclass, field
from pydantic import BaseModel, Field

from sam.stores.base import MemoryStore
from sam.embeddings import EmbeddingsService
from sam.llm_client import LLMClient
from sam.models.graph import (
    Insight, InsightCreate,
    Claim, Entity,
    EdgeType, EdgeCreate
)


# =============================================================================
# Models
# =============================================================================

class InsightCandidate(BaseModel):
    """A candidate insight generated by the LLM."""
    content: str = Field(..., description="The actionable insight text")
    supporting_claim_ids: List[str] = Field(default_factory=list)
    confidence: float = Field(default=0.6, ge=0.0, le=1.0)
    reasoning: str = Field(default="", description="Why this insight was generated")


class ConsolidationResult(BaseModel):
    """Result of a consolidation run."""
    tenant_id: str
    entity_id: Optional[str] = None
    claims_analyzed: int = 0
    insights_created: int = 0
    insights_strengthened: int = 0
    insights_merged: int = 0
    new_insight_ids: List[str] = Field(default_factory=list)
    updated_insight_ids: List[str] = Field(default_factory=list)


# =============================================================================
# Prompts
# =============================================================================

INSIGHT_DISTILLATION_PROMPT = """You are a memory consolidation system. Your job is to analyze a set of descriptive claims about entities and distill them into actionable insights.

## Claims about entities:
{claims_text}

## Your task:
Generate 1-3 actionable insights that prescribe WHAT TO DO based on these facts.

IMPORTANT DISTINCTION:
- Claims are DESCRIPTIVE: "X is true", "X happened", "X prefers Y"
- Insights are PRESCRIPTIVE: "Do X", "Prefer Y approach", "Avoid Z"

Good insight examples:
- "Contact via email for fastest response" (from claims about email preferences)
- "Provide detailed documentation rather than summaries" (from claims about user being technical)
- "Schedule meetings in morning hours" (from claims about productivity patterns)

## Output format:
Return a JSON array of insights:
```json
[
  {{
    "content": "The actionable insight",
    "supporting_claim_ids": ["claim_id_1", "claim_id_2"],
    "confidence": 0.7,
    "reasoning": "Brief explanation of why this insight follows from the claims"
  }}
]
```

If no meaningful insights can be derived, return an empty array: []

Only generate insights that are:
1. Actionable (tell what to do, not just what is true)
2. Grounded in the claims (have at least 2 supporting claims)
3. Non-obvious (add value beyond the raw claims)

Generate insights:"""


INSIGHT_SIMILARITY_PROMPT = """Compare these two insights and determine if they are semantically similar enough to merge.

Insight A: "{insight_a}"
Insight B: "{insight_b}"

Return JSON:
```json
{{
  "similar": true or false,
  "merged_content": "If similar, the merged insight text. If not similar, null.",
  "reasoning": "Brief explanation"
}}
```

Two insights should be merged if they:
1. Recommend the same or very similar action
2. Apply to the same context/situation
3. Would not conflict if both were followed

Analyze and respond:"""


