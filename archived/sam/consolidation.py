class InsightDistiller:
    """
    Distills actionable Insights from accumulated Claims.
    
    This is the core of memory consolidation - taking descriptive facts
    and converting them into prescriptive recommendations.
    """
    
    def __init__(
        self,
        store: MemoryStore,
        llm_client: LLMClient,
        embeddings: EmbeddingsService,
        min_claims_for_insight: int = 3,
        similarity_threshold: float = 0.85
    ):
        """
        Initialize the insight distiller.
        
        Args:
            store: Memory store backend
            llm_client: LLM client for generation
            embeddings: Embeddings service for similarity
            min_claims_for_insight: Minimum claims needed to generate insights
            similarity_threshold: Threshold for considering insights similar
        """
        self.store = store
        self.llm_client = llm_client
        self.embeddings = embeddings
        self.min_claims_for_insight = min_claims_for_insight
        self.similarity_threshold = similarity_threshold
    
    async def distill_for_entity(
        self,
        tenant_id: str,
        entity_id: str,
        min_confidence: float = 0.5,
        max_claims: int = 50
    ) -> ConsolidationResult:
        """
        Distill insights for a specific entity.
        
        Args:
            tenant_id: Tenant identifier
            entity_id: Entity to consolidate
            min_confidence: Minimum claim confidence to consider
            max_claims: Maximum claims to analyze at once
            
        Returns:
            ConsolidationResult with distillation statistics
        """
        result = ConsolidationResult(
            tenant_id=tenant_id,
            entity_id=entity_id
        )
        
        # Get claims for this entity
        claims = await self.store.get_claims_for_entity(
            entity_id=entity_id,
            tenant_id=tenant_id,
            limit=max_claims
        )
        
        # Filter by confidence
        claims = [c for c in claims if c.confidence >= min_confidence]
        result.claims_analyzed = len(claims)
        
        if len(claims) < self.min_claims_for_insight:
            print(f"[Consolidation] Not enough claims for entity {entity_id[:8]} ({len(claims)} < {self.min_claims_for_insight})")
            return result
        
        # Generate insight candidates
        candidates = await self._generate_insight_candidates(claims)
        
        if not candidates:
            print(f"[Consolidation] No insights generated for entity {entity_id[:8]}")
            return result
        
        # Process each candidate
        for candidate in candidates:
            insight_id = await self._process_candidate(
                candidate=candidate,
                tenant_id=tenant_id,
                result=result
            )
            
            if insight_id:
                if insight_id in result.new_insight_ids:
                    result.insights_created += 1
                else:
                    result.insights_strengthened += 1
        
        print(f"[Consolidation] Entity {entity_id[:8]}: {result.insights_created} created, {result.insights_strengthened} strengthened")
        return result
    
    async def distill_for_tenant(
        self,
        tenant_id: str,
        min_confidence: float = 0.5,
        max_entities: int = 20
    ) -> ConsolidationResult:
        """
        Run consolidation across all entities for a tenant.
        
        Args:
            tenant_id: Tenant identifier
            min_confidence: Minimum claim confidence
            max_entities: Maximum entities to process
            
        Returns:
            Aggregated ConsolidationResult
        """
        result = ConsolidationResult(tenant_id=tenant_id)
        
        # Get entities with claims
        entities = await self._get_entities_with_claims(tenant_id, limit=max_entities)
        
        print(f"[Consolidation] Processing {len(entities)} entities for tenant {tenant_id}")
        
        for entity in entities:
            entity_result = await self.distill_for_entity(
                tenant_id=tenant_id,
                entity_id=entity.id,
                min_confidence=min_confidence
            )
            
            # Aggregate results
            result.claims_analyzed += entity_result.claims_analyzed
            result.insights_created += entity_result.insights_created
            result.insights_strengthened += entity_result.insights_strengthened
            result.new_insight_ids.extend(entity_result.new_insight_ids)
            result.updated_insight_ids.extend(entity_result.updated_insight_ids)
        
        return result
    
    async def _generate_insight_candidates(
        self,
        claims: List[Claim]
    ) -> List[InsightCandidate]:
        """Generate insight candidates from claims using LLM."""
        # Format claims for prompt
        claims_text = "\n".join([
            f"- [{c.id[:8]}] {c.content} (confidence: {c.confidence:.2f})"
            for c in claims
        ])
        
        prompt = INSIGHT_DISTILLATION_PROMPT.format(claims_text=claims_text)
        
        try:
            response = await self.llm_client.complete_json(
                prompt=prompt,
                system="You are a memory consolidation system that distills actionable insights from facts."
            )
            
            if isinstance(response, list):
                candidates = []
                for item in response:
                    try:
                        candidates.append(InsightCandidate(**item))
                    except Exception as e:
                        print(f"[Consolidation] Failed to parse candidate: {e}")
                return candidates
            
            return []
            
        except Exception as e:
            print(f"[Consolidation] LLM insight generation failed: {e}")
            return []
    
    async def _process_candidate(
        self,
        candidate: InsightCandidate,
        tenant_id: str,
        result: ConsolidationResult
    ) -> Optional[str]:
        """
        Process an insight candidate - create new or merge with existing.
        
        Returns the insight ID if processed, None otherwise.
        """
        # Generate embedding for the candidate
        embedding = self.embeddings.embed_text(candidate.content)
        
        # Check for similar existing insights
        similar = await self.store.find_similar_insights(
            embedding=embedding,
            tenant_id=tenant_id,
            limit=5,
            min_similarity=self.similarity_threshold
        )
        
        if similar:
            # Merge with the most similar existing insight
            existing = similar[0]
            await self._merge_insights(
                existing=existing,
                candidate=candidate,
                tenant_id=tenant_id
            )
            result.updated_insight_ids.append(existing.id)
            result.insights_merged += 1
            return existing.id
        
        else:
            # Create new insight
            insight = await self.store.create_insight(InsightCreate(
                tenant_id=tenant_id,
                content=candidate.content,
                confidence=candidate.confidence,
                source_claim_ids=candidate.supporting_claim_ids,
                metadata={
                    "reasoning": candidate.reasoning,
                    "generated_at": datetime.utcnow().isoformat()
                }
            ))
            
            # Update embedding
            await self._update_insight_embedding(insight.id, tenant_id, embedding)
            
            result.new_insight_ids.append(insight.id)
            return insight.id
    
    async def _merge_insights(
        self,
        existing: Insight,
        candidate: InsightCandidate,
        tenant_id: str
    ) -> None:
        """Merge a candidate into an existing insight."""
        # Increase confidence (but cap at 1.0)
        new_confidence = min(1.0, existing.confidence + 0.1)
        
        # Add new source claims
        new_source_ids = list(set(
            existing.source_claim_ids + candidate.supporting_claim_ids
        ))
        
        # Update the insight
        await self.store.update_insight(
            insight_id=existing.id,
            tenant_id=tenant_id,
            confidence=new_confidence,
            source_claim_ids=new_source_ids
        )
        
        # Create SUPPORTS edges for new claims
        for claim_id in candidate.supporting_claim_ids:
            if claim_id not in existing.source_claim_ids:
                try:
                    await self.store.create_edge(EdgeCreate(
                        tenant_id=tenant_id,
                        source_id=claim_id,
                        target_id=existing.id,
                        edge_type=EdgeType.SUPPORTS
                    ))
                except Exception:
                    pass  # Edge might already exist
        
        print(f"[Consolidation] Merged into insight {existing.id[:8]}, confidence: {new_confidence:.2f}")
    
    async def _update_insight_embedding(
        self,
        insight_id: str,
        tenant_id: str,
        embedding: List[float]
    ) -> None:
        """Update the embedding for an insight."""
        if hasattr(self.store, '_get_conn'):
            from sam.stores.sqlite_store import _serialize_embedding
            conn = self.store._get_conn()
            conn.execute("""
                UPDATE insights SET embedding = ? 
                WHERE id = ? AND tenant_id = ?
            """, (_serialize_embedding(embedding), insight_id, tenant_id))
            conn.commit()
    
    async def _get_entities_with_claims(
        self,
        tenant_id: str,
        limit: int = 20
    ) -> List[Entity]:
        """Get entities that have claims."""
        if hasattr(self.store, '_get_conn'):
            conn = self.store._get_conn()
            
            # Get entities that have claims (via ABOUT edges)
            rows = conn.execute("""
                SELECT DISTINCT e.* FROM entities e
                JOIN edges ed ON ed.target_id = e.id AND ed.edge_type = 'ABOUT'
                WHERE e.tenant_id = ?
                ORDER BY e.last_accessed DESC
                LIMIT ?
            """, (tenant_id, limit)).fetchall()
            
            return [self.store._row_to_entity(row) for row in rows]
        
        return []


